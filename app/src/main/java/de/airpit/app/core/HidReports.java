package de.airpit.app.core;

/** Standard Bluetooth HID: relative mouse + six-key-rollover keyboard. */
public final class HidReports {
    private HidReports() {}
    public static final int MOUSE = 1, KEYBOARD = 2;
    public static final byte[] DESCRIPTOR = bytes(
        0x05,0x01, 0x09,0x02, 0xA1,0x01, 0x85,0x01, 0x09,0x01, 0xA1,0x00,
        0x05,0x09, 0x19,0x01, 0x29,0x03, 0x15,0x00, 0x25,0x01, 0x95,0x03, 0x75,0x01, 0x81,0x02,
        0x95,0x01, 0x75,0x05, 0x81,0x03,
        0x05,0x01, 0x09,0x30, 0x09,0x31, 0x09,0x38, 0x15,0x81, 0x25,0x7F, 0x75,0x08, 0x95,0x03, 0x81,0x06,
        0xC0,0xC0,
        0x05,0x01, 0x09,0x06, 0xA1,0x01, 0x85,0x02,
        0x05,0x07, 0x19,0xE0, 0x29,0xE7, 0x15,0x00, 0x25,0x01, 0x75,0x01, 0x95,0x08, 0x81,0x02,
        0x95,0x01, 0x75,0x08, 0x81,0x03,
        0x95,0x05, 0x75,0x01, 0x05,0x08, 0x19,0x01, 0x29,0x05, 0x91,0x02,
        0x95,0x01, 0x75,0x03, 0x91,0x03,
        0x95,0x06, 0x75,0x08, 0x15,0x00, 0x25,0x65, 0x05,0x07, 0x19,0x00, 0x29,0x65, 0x81,0x00, 0xC0
    );
    public static byte[] mouse(int buttons, int x, int y, int wheel) {
        return bytes(buttons & 7, clamp(x), clamp(y), clamp(wheel));
    }
    public static byte[] keyboard(int modifiers, int key) {
        return bytes(modifiers, 0, key, 0, 0, 0, 0, 0);
    }
    public static int clamp(int n) { return Math.max(-127, Math.min(127,n)); }
    private static byte[] bytes(int... values) {
        byte[] b = new byte[values.length];
        for(int i=0;i<b.length;i++) b[i]=(byte)values[i];
        return b;
    }
}
